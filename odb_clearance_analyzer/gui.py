def _is_real_voltage_net_name(name: object) -> bool:
    """Return True for net names that are useful for voltage guessing.

    ODB++ often uses ``$NONE$`` for anonymous copper.  Voltage guessing
    should not create assignments for those placeholder nets, but it should
    be tolerant of real net names discovered from analysis outputs even when
    the EDA net table is incomplete or stale.
    """

    text = str(name or "").strip()
    return bool(text) and text.upper() != "$NONE$"


def _collect_voltage_net_names_from_job(job: object | None) -> set[str]:
    """Collect voltage-guessing candidate nets from parsed ODB++ metadata."""

    if job is None:
        return set()

    nets: set[str] = set()

    try:
        named_nets = getattr(job, "named_nets")
        if callable(named_nets):
            named_nets = named_nets()
        for net in named_nets:
            if _is_real_voltage_net_name(net):
                nets.add(str(net).strip())
    except Exception:
        pass

    try:
        for net in getattr(job, "nets_by_number", {}).values():
            if _is_real_voltage_net_name(net):
                nets.add(str(net).strip())
    except Exception:
        pass

    try:
        for net in getattr(job, "feature_net_map", {}).values():
            if _is_real_voltage_net_name(net):
                nets.add(str(net).strip())
    except Exception:
        pass

    return nets


def _collect_voltage_net_names_from_result(result: object | None) -> set[str]:
    """Collect voltage-guessing candidate nets from a completed analysis.

    Full analysis can contain reliable net names in several places.  Earlier
    GUI builds only read ``result.job.named_nets``; if that source was empty,
    Auto-detect incorrectly warned the user to run analysis even though a
    completed analysis was already loaded.  This helper deliberately falls
    back to geometry and report records generated by the analysis.
    """

    if result is None:
        return set()

    nets = _collect_voltage_net_names_from_job(getattr(result, "job", None))

    try:
        for by_net in getattr(result, "net_geometry_by_layer", {}).values():
            for net in by_net.keys():
                if _is_real_voltage_net_name(net):
                    nets.add(str(net).strip())
    except Exception:
        pass

    try:
        for rec in getattr(result, "per_net_minimum", []) or []:
            for attr in ("net", "other_net"):
                net = getattr(rec, attr, "")
                if _is_real_voltage_net_name(net):
                    nets.add(str(net).strip())
    except Exception:
        pass

    try:
        records = list(getattr(result, "measurements", []) or []) + list(getattr(result, "critical_measurements", []) or [])
        for rec in records:
            for attr in ("net_a", "net_b"):
                net = getattr(rec, attr, "")
                if _is_real_voltage_net_name(net):
                    nets.add(str(net).strip())
    except Exception:
        pass

    return nets

def _load_packaged_photoimage(name: str, master=None) -> PhotoImage | None:
    """Load a PNG image shipped inside the package.

    Returns ``None`` if the asset is missing or Tk cannot load it.
    """

    try:
        ref = resources.files("odb_clearance_analyzer").joinpath("assets", name)
        with resources.as_file(ref) as asset_path:
            return PhotoImage(master=master, file=str(asset_path))
    except Exception:
        return None


