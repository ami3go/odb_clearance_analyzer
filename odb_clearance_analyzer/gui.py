        tree.bind("A", lambda _e: _act("approve"))
        tree.bind("u", lambda _e: _act("accept_unknown"))
        tree.bind("U", lambda _e: _act("accept_unknown"))
        tree.bind("w", lambda _e: _act("waive"))
        tree.bind("W", lambda _e: _act("waive"))
        tree.bind("e", _edit)
        tree.bind("E", _edit)
        tree.bind("s", _skip)
        tree.bind("S", _skip)
        tree.bind("?", _why)
        tree.bind("<Return>", _why)

