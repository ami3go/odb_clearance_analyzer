    @staticmethod
    def _common_voltage_assignment_value(assignments: list[VoltageAssignment], getter) -> tuple[bool, object | None]:
        if not assignments:
            return False, None
        values = [getter(assignment) for assignment in assignments]
        first = values[0]
        return any(value != first for value in values[1:]), first

    def _on_voltage_assignment_selected(self) -> None:
        nets = self._selected_voltage_assignment_nets()
        if not nets:
            return
        assignments = [self.voltage_assignments[net] for net in nets]
        if len(nets) == 1:
            self.voltage_selected_net.set(nets[0])
        else:
            preview = ", ".join(nets[:4])
            if len(nets) > 4:
                preview += ", ..."
            self.voltage_selected_net.set(f"{len(nets)} selected: {preview}")

        mixed, value = self._common_voltage_assignment_value(assignments, lambda a: a.final_class)
        self.voltage_final_class.set(_MIXED_CLASS_SELECTION if mixed else str(value or "UNKNOWN"))

        mixed, value = self._common_voltage_assignment_value(assignments, lambda a: a.final_voltage_v)
        if mixed:
            self.voltage_final_voltage.set(_MIXED_VOLTAGE_SELECTION)
        else:
            self.voltage_final_voltage.set("" if value is None else f"{float(value):g}")

        mixed, value = self._common_voltage_assignment_value(assignments, lambda a: a.review_state)
        self.voltage_review_state.set(_MIXED_REVIEW_SELECTION if mixed else str(value or "Reviewed"))

        mixed, value = self._common_voltage_assignment_value(assignments, lambda a: a.notes)
        self.voltage_notes.set("" if mixed or value is None else str(value))

    def _apply_voltage_manual_override(self) -> None:
        nets = self._selected_voltage_assignment_nets()
        if not nets:
            messagebox.showinfo("Voltage Guessing", "Select one or more net assignments first.")
            return

        final_class = self.voltage_final_class.get().strip()
        if not final_class or final_class == _MIXED_CLASS_SELECTION or final_class not in NET_CLASSES:
            messagebox.showerror("Voltage Guessing", "Choose one valid voltage class before applying the bulk edit.")
            return

        review_state = self.voltage_review_state.get().strip()
        if not review_state or review_state == _MIXED_REVIEW_SELECTION or review_state not in REVIEW_STATES:
            messagebox.showerror("Voltage Guessing", "Choose one valid review state before applying the bulk edit.")
            return

        voltage_text = self.voltage_final_voltage.get().strip()
        if voltage_text == _MIXED_VOLTAGE_SELECTION:
            messagebox.showerror("Voltage Guessing", "Enter one voltage value, or clear the voltage field, before applying the bulk edit.")
            return
        if voltage_text == "":
            voltage = None
        else:
            try:
                voltage = float(voltage_text)
            except Exception:
                messagebox.showerror("Voltage Guessing", f"Invalid voltage value: {voltage_text!r}")
                return

        try:
            changed = review_service.apply_manual_override_bulk(
                self.voltage_store,
                nets,
                final_class=final_class,
                final_voltage_v=voltage,
                review_state=review_state,
                notes=self.voltage_notes.get().strip(),
            )
        except (KeyError, ValueError) as exc:
            messagebox.showerror("Voltage Guessing", str(exc))
            return

        self._save_voltage_store_safely()
        self._refresh_voltage_views()
        tree = self.voltage_assignment_tree
        if tree is not None:
            existing = [net for net in nets if tree.exists(net)]
            if existing:
                tree.selection_set(*existing)
                tree.see(existing[0])
                self._on_voltage_assignment_selected()
        self._append_log(f"Voltage Guessing: manual override applied to {changed} selected net(s).")

