    def _voltage_review_action(self, action: str) -> None:
        nets = self._selected_review_nets()
        if not nets:
            messagebox.showinfo("Voltage Guessing", "Select one or more nets in the review queue first.")
            return
        reason = ""
        final_class = None
        final_voltage = None
        if action == "waive":
            reason = simpledialog.askstring("Waive nets", f"Waiver reason for {len(nets)} net(s):", parent=self.master) or ""
            if not reason.strip():
                return
        elif action == "accept_unknown":
            reason = simpledialog.askstring("Accept unknown", f"Reason for accepting unknown voltage on {len(nets)} net(s):", parent=self.master) or ""
        elif action == "set_class_voltage":
            final_class = simpledialog.askstring("Set class", "Final class:", initialvalue=self.voltage_final_class.get() or "UNKNOWN", parent=self.master)
            if not final_class:
                return
            raw_voltage = simpledialog.askstring("Set voltage", "Final voltage V (blank = unknown):", parent=self.master)
            if raw_voltage is None:
                return
            raw_voltage = raw_voltage.strip()
            if raw_voltage:
                try:
                    final_voltage = float(raw_voltage)
                except Exception:
                    messagebox.showerror("Voltage Guessing", f"Invalid voltage value: {raw_voltage!r}")
                    return
            reason = simpledialog.askstring("Batch reason", f"Review reason for {len(nets)} net(s):", parent=self.master) or ""
        preview = phase4.make_batch_preview(
            self.voltage_store, nets, action, final_class=final_class, final_voltage_v=final_voltage, reason=reason.strip()
        )
        if not messagebox.askyesno("Batch review dry-run preview", phase4.preview_to_text(preview) + "\n\nApply changes?"):
            return
        count = phase4.apply_batch_action(
            self.voltage_store, nets, action, final_class=final_class, final_voltage_v=final_voltage,
            reason=reason.strip(), waiver_scope=self.voltage_waiver_scope.get(),
        )
        self._save_voltage_store_safely()
        self._refresh_voltage_views()
        self._append_log(f"Voltage Guessing: {action} applied to {count} net(s).")

