    def _current_voltage_rule_pack(self):
        """Built-in pack layered with project-local correction rules.

        The cache is invalidated whenever the project rule directory
        changes or a correction rule is created (Phase 4 gate 3)."""
        rule_dir = self._phase4_project_rule_dir()
        if self.voltage_rule_pack is None or getattr(self, "_voltage_rule_pack_dir", None) != str(rule_dir):
            self.voltage_rule_pack = load_layered_rule_pack(rule_dir)
            self._voltage_rule_pack_dir = str(rule_dir)
        return self.voltage_rule_pack

    def _invalidate_voltage_rule_pack(self) -> None:
        self.voltage_rule_pack = None

    def _current_voltage_net_names(self) -> list[str]:
        nets = _collect_voltage_net_names_from_result(self.last_result)
        if not nets:
            nets = _collect_voltage_net_names_from_job(self.last_metadata_job)
        return sorted(nets)

    def _voltage_project_revision(self) -> str:
        if self.last_result is not None:
            return str(self.last_result.job.step_name or "")
        if self.last_metadata_job is not None:
            return str(getattr(self.last_metadata_job, "step_name", "") or "")
        if self.odb_path.get().strip():
            return Path(self.odb_path.get()).stem
        return ""

    def _run_voltage_auto_detect(self) -> None:
        nets = self._current_voltage_net_names()
        if not nets:
            messagebox.showinfo("Voltage Guessing", "Read ODB++ metadata or run analysis first.")
            return
        if self.voltage_assignments:
            preview = (
                f"Auto-detect voltage classes will evaluate {len(nets)} current net(s).\n"
                f"Existing manual/imported assignments are preserved.\n"
                f"Current assignments: {len(self.voltage_assignments)}.\n\nApply auto-detect now?"
            )
            if not messagebox.askyesno("Auto-detect dry-run preview", preview):
                return
        rule_pack = self._current_voltage_rule_pack()
        changed = review_service.run_auto_detect(
            self.voltage_store, nets, rule_pack, source_revision=self._voltage_project_revision()
        )
        self._save_voltage_store_safely()
        self._refresh_voltage_views()
        self._append_log(
            f"Voltage Guessing: auto-detect changed {changed} assignment(s); manual and imported values preserved."
        )

    def _refresh_voltage_assignment_table(self) -> None:
        tree = self.voltage_assignment_tree
        if tree is None:
            return
        for item in tree.get_children():
            tree.delete(item)
        for idx, assignment in enumerate(sorted(self.voltage_assignments.values(), key=lambda a: a.net_name)):
            tag = "even" if idx % 2 == 0 else "odd"
            if assignment.severity == "Critical":
                tag = "severity_critical"
            elif assignment.severity == "Warning":
                tag = "severity_warning"
            if assignment.source == "manual":
                tag = "manual"
            warning = assignment.evidence.rule_warning or assignment.evidence.manual_review_note or assignment.review_reason
            if assignment.waiver.waived:
                warning = f"WAIVED ({assignment.waiver.waiver_scope}): {assignment.waiver.waiver_reason}"
            tree.insert(
                "",
                END,
                iid=assignment.net_name,
                values=(
                    assignment.net_name,
                    assignment.final_class,
                    "" if assignment.final_voltage_v is None else f"{assignment.final_voltage_v:g}",
                    assignment.confidence,
                    assignment.severity,
                    assignment.source,
                    assignment.review_state,
                    assignment.evidence.matched_rule_id,
                    warning,
                ),
                tags=(tag,),
            )

