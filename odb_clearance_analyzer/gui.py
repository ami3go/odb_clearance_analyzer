    def _parse_isolation_nets(self) -> list[str]:
        """Parse isolated-side net names from text box."""

        if not hasattr(self, "isolation_nets_text"):
            return []
        raw = self.isolation_nets_text.get("1.0", END)
        tokens = [token.strip() for token in re.split(r"[,;\\s]+", raw) if token.strip()]
        # Preserve order while removing duplicates.
        seen = set()
        result = []
        for token in tokens:
            if token not in seen:
                result.append(token)
                seen.add(token)
        return result

    def _isolation_required_values(self) -> tuple[float, float, float]:
        """Return required clearance, creepage and governing spacing in mm."""

        clearance = max(0.0, float(self.isolation_required_clearance_mm.get()))
        creepage = max(0.0, float(self.isolation_required_creepage_mm.get()))
        factor = max(0.0, float(self.isolation_safety_factor.get()))
        required = max(clearance, creepage) * factor
        return clearance, creepage, required

    def _calculate_isolation_spacing(self) -> None:
        """Calculate isolated-side spacing to every other net on each layer."""

        if self.last_result is None:
            messagebox.showinfo("IEC 61558 / IEC 62368", "Run a main analysis first.")
            return

        isolated_nets = set(self._parse_isolation_nets())
        if not isolated_nets:
            messagebox.showinfo("IEC 61558 / IEC 62368", "Enter at least one isolated-side net.")
            return

        clearance, creepage, required = self._isolation_required_values()
        standard = self.isolation_standard.get()
        group = self.isolation_group_name.get().strip() or "Isolated side"
        records = []

        for layer, by_net in self.last_result.net_geometry_by_layer.items():
            layer_iso = [net for net in isolated_nets if net in by_net]
            if not layer_iso:
                continue
            for iso_net in sorted(layer_iso):
                geom_a = by_net.get(iso_net)
                if geom_a is None or getattr(geom_a, "is_empty", True):
                    continue
                for other_net, geom_b in by_net.items():
                    if other_net in isolated_nets:
                        continue
                    if geom_b is None or getattr(geom_b, "is_empty", True):
                        continue
                    try:
                        measured = float(geom_a.distance(geom_b))
                    except Exception:
                        continue
                    margin = measured - required
                    records.append(
                        {
                            "group": group,
                            "layer": layer,
                            "isolated_net": iso_net,
                            "other_net": other_net,
                            "measured_mm": measured,
                            "required_clearance_mm": clearance,
                            "required_creepage_mm": creepage,
                            "required_mm": required,
                            "margin_mm": margin,
                            "result": "PASS" if margin >= 0 else "FAIL",
                            "standard": standard,
                        }
                    )

        records.sort(key=lambda row: (row["margin_mm"], row["measured_mm"], row["layer"], row["isolated_net"], row["other_net"]))
        self.visible_isolation_records = records
        self._fill_isolation_table(records)
        missing = sorted(isolated_nets - {row["isolated_net"] for row in records})
        missing_text = "" if not missing else f" Missing/not present in compared layers: {', '.join(missing)}."
        self.isolation_status.set(
            f"Calculated {len(records)} isolated-side pair(s). Required spacing={required:g} mm. "
            f"Fails={sum(1 for row in records if row['result'] == 'FAIL')}.{missing_text}"
        )

    def _fill_isolation_table(self, records: list[dict[str, object]]) -> None:
        """Fill isolated-side spacing table."""

        for iid in self.isolation_tree.get_children():
            self.isolation_tree.delete(iid)
        for idx, row in enumerate(records[:5000]):
            margin = float(row["margin_mm"])
            measured = float(row["measured_mm"])
            tag = self._clearance_row_tag(measured, idx) if bool(self.clearance_gradient.get()) else ("critical" if margin < 0 else ("even" if idx % 2 == 0 else "odd"))
            self.isolation_tree.insert(
                "",
                END,
                iid=f"isolation-{idx}",
                tags=(tag,),
                values=(
                    row["group"],
                    row["layer"],
                    row["isolated_net"],
                    row["other_net"],
                    f"{float(row['measured_mm']):.6f}",
                    f"{float(row['required_clearance_mm']):.6f}",
                    f"{float(row['required_creepage_mm']):.6f}",
                    f"{float(row['required_mm']):.6f}",
                    f"{float(row['margin_mm']):.6f}",
                    row["result"],
                    row["standard"],
                ),
            )

